# Pre-build: stamp the firmware with a build id ("20261112-0415-ab12cd3", "+d" = uncommitted changes).
# Writes src/tzt-display/FwVersion.cpp or src/FwVersion.cpp (Main) (only when the id changes, so just that file recompiles) and
# $BUILD_DIR/fw_version.txt, which scripts/publish_firmware.py sends to the Pi with firmware.bin.
# The TZT reports its id on every poll; the Pi offers the published build until they match.
Import("env")
import os
import subprocess
import time

project = env["PROJECT_DIR"]


def git(*args):
    try:
        return subprocess.run(["git", *args], cwd=project, capture_output=True, text=True, timeout=5).stdout.strip()
    except Exception:
        return ""


version = time.strftime("%Y%m%d-%H%M")
commit = git("rev-parse", "--short=7", "HEAD")
if commit:
    version += "-" + commit + ("+d" if git("status", "--porcelain", "--untracked-files=no") else "")

# TZT envs compile src/tzt-display/ only; Main envs compile src/ minus tzt-display/
is_tzt = env["PIOENV"].startswith("tzt")
src = os.path.join(project, "src", "tzt-display", "FwVersion.cpp") if is_tzt else os.path.join(project, "src", "FwVersion.cpp")
content = ('// Generated by scripts/fw_version.py - do not edit\n'
           '#include "FwVersion.h"\n'
           'const char FW_VERSION[] = "%s";\n' % version)
try:
    old = open(src).read()
except OSError:
    old = ""
if old != content:
    with open(src, "w") as f:
        f.write(content)

build_dir = env.subst("$BUILD_DIR")
os.makedirs(build_dir, exist_ok=True)
with open(os.path.join(build_dir, "fw_version.txt"), "w") as f:
    f.write(version)
print("[fw_version] " + version)
